num = 1  # 初始数字，从1开始
i = 0    # 外层循环变量，控制行数（0-4，共5行）

# 外层循环：控制5行
while i < 5:
    j = 0  # 内层循环变量，控制每行的5列
    # 内层循环：控制每行的5个数字
    while j < 5:
        print(num, end=" ")  # 打印当前数字，用空格分隔
        num += 1  # 数字递增
        j += 1    # 列变量自增，准备打印下一列
    print()  # 每行结束后换行
    i += 1    # 行变量自增，准备打印下一行